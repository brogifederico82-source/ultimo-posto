function syncBackgroundMusic(){
  musicArea="entrance";
  if(screen==="game"&&state&&!atViale(state)){
    musicArea=["dome","tutorato","terzo"].includes(state.zone)?"study":"campus";
  }
  const nextMusic=musicPlaylists[musicArea][musicPosition[musicArea]];
  if(currentMusic!==nextMusic){
    pauseMusic();
    currentMusic=nextMusic;
    musicFailed=false;
  }
  if(!audioOn||currentMusic.volume===0){
    pauseMusic();
    setMusicStatus(audioOn?"muted":"");
    return;
  }
  setMusicStatus(musicFailed?"unavailable":"");
  if(musicStart||musicFailed||!currentMusic.paused)return;
  const attempt=currentMusic.play();
  musicStart=attempt;
  attempt?.then(()=>{
    if(musicStart!==attempt)return;
    musicStart=null;
  },()=>{
    if(musicStart!==attempt)return;
    musicStart=null;
    musicFailed=true;
    setMusicStatus("unavailable");
  });
}
